def _drift_name(name: str) -> str:
    """Generate a drifted field name using synonym map or suffix transformation."""
    if name in DRIFT_SYNONYMS:
        return DRIFT_SYNONYMS[name]
    # Fallback: append _value or swap underscores
    if "_" in name:
        parts = name.split("_")
        return "_".join(reversed(parts))
    return f"{name}_value"


# ═══════════════════════════════════════════════════════════════
# AST PARSER — extract function signatures from api.py
# ═══════════════════════════════════════════════════════════════

def _parse_api_file(filepath: str) -> List[Dict[str, Any]]:
    """Parse a ToolBench api.py file and extract tool schemas."""
    with open(filepath, "r") as f:
        source = f.read()

    try:
        tree = ast.parse(source)
    except SyntaxError:
        return []

    tools = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.FunctionDef):
            continue

        name = node.name
        if name.startswith("_"):
            continue

        # Extract docstring
        docstring = ast.get_docstring(node) or ""
        description = docstring.split("\n")[0].strip().strip('"').strip()

        # Extract parameters (skip toolbench_rapidapi_key)
        params = {}
        required = []
        defaults_map = {}

        # Build defaults mapping
        args = node.args
        num_defaults = len(args.defaults)
        num_args = len(args.args)
        for i, arg in enumerate(args.args):
            pname = arg.arg
            if pname in ("self", "toolbench_rapidapi_key"):
                continue

            # Get type annotation
            ptype = "string"
            if arg.annotation:
                ann = ast.dump(arg.annotation)
                if "int" in ann:
                    ptype = "integer"
                elif "float" in ann:
                    ptype = "number"
                elif "bool" in ann:
                    ptype = "boolean"

            # Check if has default
            default_idx = i - (num_args - num_defaults)
            has_default = default_idx >= 0
            default_val = None
            if has_default:
                d = args.defaults[default_idx]
                if isinstance(d, ast.Constant):
                    default_val = d.value

            # Extract description from docstring
            pdesc = ""
            for line in docstring.split("\n"):
                if pname + ":" in line or pname + " " in line:
                    pdesc = line.split(":", 1)[-1].strip() if ":" in line else ""
                    break

            params[pname] = {
                "type": ptype,
                "description": pdesc or f"Parameter: {pname}",
            }
            if default_val is not None:
                defaults_map[pname] = default_val

            if not has_default:
                required.append(pname)

        if not params and not description:
            continue

        tools.append({
            "name": name,
            "description": description or f"Tool: {name}",
            "params": params,
            "required": required,
            "defaults": defaults_map,
        })

    return tools


# ═══════════════════════════════════════════════════════════════
# SCHEMA BUILDER — generates V1/V2 + MCP format
# ═══════════════════════════════════════════════════════════════

def _build_tool_entry(tool: Dict, domain: str, api_name: str) -> Dict[str, Any]:
    """Build a full tool registry entry with V1 and V2 schemas."""
    v1_fields = list(tool["params"].keys())
    v2_fields = [_drift_name(f) for f in v1_fields]

    v1_schema = {f: tool["params"][f].get("description", "") for f in v1_fields}
    v2_schema = {v2: tool["params"][v1].get("description", "")
                 for v1, v2 in zip(v1_fields, v2_fields)}

    # Generate deterministic mock response based on tool name
    h = int(hashlib.md5(tool["name"].encode()).hexdigest()[:8], 16)

    return {
        "name": f"{api_name}__{tool['name']}",
        "description": tool["description"],
        "category": domain,
        "api": api_name,
        "required": tool["required"],
        "defaults": tool["defaults"],
        "v1_fields": v1_fields,
        "v2_fields": v2_fields,
        "v1_schema": v1_schema,
        "v2_schema": v2_schema,
        "params": tool["params"],
        "inputSchema": {
            "type": "object",
            "properties": {
                f: {"type": tool["params"][f]["type"],
                    "description": tool["params"][f]["description"]}
                for f in v1_fields
            },
            "required": tool["required"],
        },
    }


