def load_toolbench_schemas(tools_dir: str) -> Dict[str, Dict]:
    """
    Parse all ToolBench api.py files and return a unified tool registry.

    Returns:
        {tool_name: {description, category, v1_fields, v2_fields, v1_schema, v2_schema, ...}}
    """
    registry = {}
    stats = {"domains": set(), "apis": 0, "tools": 0, "params": 0}

    for domain in sorted(os.listdir(tools_dir)):
        domain_path = os.path.join(tools_dir, domain)
        if not os.path.isdir(domain_path) or domain.startswith("."):
            continue

        for api_name in sorted(os.listdir(domain_path)):
            api_path = os.path.join(domain_path, api_name)
            api_file = os.path.join(api_path, "api.py")
            if not os.path.isfile(api_file):
                continue

            tools = _parse_api_file(api_file)
            if not tools:
                continue

            stats["apis"] += 1
            stats["domains"].add(domain)

            for tool in tools:
                entry = _build_tool_entry(tool, domain, api_name)
                registry[entry["name"]] = entry
                stats["tools"] += 1
                stats["params"] += len(tool["params"])

    print(f"ToolBench loaded: {len(stats['domains'])} domains, "
          f"{stats['apis']} APIs, {stats['tools']} tools, "
          f"{stats['params']} total parameters",
          file=__import__('sys').stderr)

    return registry


def get_summary(registry: Dict) -> Dict:
    """Get a summary of the loaded registry by domain."""
    by_domain = {}
    for name, entry in registry.items():
        d = entry["category"]
        by_domain.setdefault(d, {"tools": 0, "params": 0, "apis": set()})
        by_domain[d]["tools"] += 1
        by_domain[d]["params"] += len(entry["v1_fields"])
        by_domain[d]["apis"].add(entry["api"])
    for d in by_domain:
        by_domain[d]["apis"] = len(by_domain[d]["apis"])
    return by_domain


